/** Opis ćwiczenia po dotknięciu: jak je zrobić, na co uważać i najczęstszy błąd. */
data class ExerciseInfo(
    val name: String,
    val muscles: Set<Muscle>,
    val how: String,
    val tips: List<String>,
    val mistake: String,
    /** Fraza do wyszukania wideo; domyślnie nazwa. */
    val videoQuery: String = name,
) {
    val videoUrl: String
        get() = "https://www.youtube.com/results?search_query=" + URLEncoder.encode("$videoQuery technika", "UTF-8")
}

